"""Draft a loadable spendcube YAML config from a profile (profiler.profile_file). Human edits the TODOs.

`draft_config(profile, ...) -> str`, `main_profile(args)` (CLI: profile --file --taxonomy --draft-config).
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Optional

from .profiler import format_report, profile_file


def _q(s: Any) -> str:
    return json.dumps(str(s), ensure_ascii=False)


def _lst(xs) -> str:
    return "[" + ", ".join(_q(x) for x in xs) + "]"


def draft_config(profile: dict, file_path: str | Path, taxonomy_path: Optional[str | Path] = None,
                 company: str = "C", reporting_currency: str = "USD", candidate_name: str = "jaygautam",
                 llm_include: Optional[str] = "../configs/_llm.yaml", input_dir: Optional[str] = None,
                 industry_hint: str = "TODO: one line about the company's industry (helps the LLM)",
                 accept_suggestions: bool = False) -> str:
    r = profile["roles"]
    fp, in_dir = Path(file_path), input_dir or str(Path(file_path).parent)
    L: list[str] = []
    A = L.append
    A("# DRAFT config generated by `spendcube profile`. Review every TODO before the full run.")
    A("# Run: python -m spendcube run --config submission/C.yaml --out submission --no-llm --limit 2000   (smoke)")
    if llm_include:
        A(f"include: [{_q(llm_include)}]      # LLM chain/roles (path relative to this file)")
    A(f"company: {company}")
    A(f"candidate_name: {candidate_name}")
    A(f"reporting_currency: {reporting_currency}        # TODO confirm (the brief says USD for C)")
    A(f"industry_hint: {_q(industry_hint)}")
    A(f"input_dir: {_q(in_dir)}")
    A("")
    t = profile.get("taxonomy", {})
    if taxonomy_path:
        A("taxonomy:")
        A(f"  file: {_q('{input_dir}/' + Path(taxonomy_path).name)}")
        A(f"  format: {t.get('detected_format', 'auto') if t.get('ok') else 'auto'}      # wide | path | adjacency | auto"
          f"{'   # parsed: ' + t['summary'] if t.get('ok') else '   # TODO taxonomy did not parse: ' + str(t.get('error'))}")
        A('  path_separator: " > "                # only for format=path (auto-detected otherwise)')
    else:
        A("taxonomy:")
        A('  file: "{input_dir}/TODO_taxonomy.csv"   # TODO')
        A("  format: auto")
    A("")
    meta = profile["meta"]
    A("sources:")
    A("  - name: lines")
    A("    role: primary")
    A(f"    file: {_q('{input_dir}/' + fp.name)}")
    A(f"    read: {{delimiter: {_q(meta['delimiter'])}, encoding: auto}}")
    if "line_id" in r:
        U = profile["columns"][r["line_id"]]["unique_ratio"]
        A(f"    record_id: {{column: {_q(r['line_id'])}, prefix: \"\"}}" + ("" if U >= 0.99 else f"   # WARNING unique ratio {U:.2f}: duplicated ids get #n suffixes"))
    else:
        A('    record_id: {column: null, prefix: ""}     # TODO no id column found: row numbers are used')
    am = profile.get("amounts", {})
    if am.get("decimal") == ",":
        A('    number_format: {decimal: ","}              # European decimals detected')
    A("    columns:")

    def col(key, role=None, comment=""):
        role = role or key
        if role in r:
            A(f"      {key}: {_q(r[role])}{('   # ' + comment) if comment else ''}")
        else:
            A(f"      # {key}: TODO not found")
    col("supplier_name")
    col("vendor_id")
    dc = profile.get("description_columns") or []
    if len(dc) > 1:
        A(f"      description: {_lst(dc)}")
    elif dc:
        A(f"      description: {_q(dc[0])}")
    else:
        A("      # description: TODO not found")
    col("material_id")
    col("quantity")
    col("uom")
    col("amount")
    basis = am.get("basis_hint", "unknown")
    A(f"      amount_basis: {'gross' if basis.startswith('gross') else 'net'}      # hint={basis}"
      f"{'  TODO confirm (net amounts need no VAT removal)' if basis in ('unknown', 'gross?') else ''}")
    if "tax_rate" in r:
        col("tax_rate")
        A("      default_tax_rate: 0.15          # TODO used only when the rate cell is blank; set the company's standard VAT")
    elif "tax_amount" in r:
        col("tax_amount")
    elif basis.startswith("gross"):
        A("      default_tax_rate: 0.15          # TODO gross amounts but no tax column: set the standard VAT rate")
    if "currency" in r:
        col("currency")
    else:
        A(f"      currency_constant: {reporting_currency}    # TODO no currency column")
    if "fx_rate" in r:
        col("fx_rate", comment="per-line rate; check fx_rate_convention below")
        A("      fx_rate_convention: units_per_reporting     # or reporting_per_unit")
    dates = profile.get("dates", {})
    for role in ("invoice_date", "posting_date"):
        if role in dates:
            d = dates[role]
            A(f"      {role}: {{column: {_q(d['column'])}, dayfirst: {str(d['dayfirst']).lower()}}}"
              f"{'   # TODO ambiguous dd/mm vs mm/dd: confirm' if d['ambiguous'] else ''}")
        else:
            A(f"      # {role}: not found (optional)")
    col("status")
    col("po_reference")
    col("invoice_number")
    col("gl_account")
    col("gl_description")
    col("cost_centre")
    used = set(r.values()) | set(dc)
    extra = [c for c, f in profile["columns"].items() if c not in used and f["kind"] in ("text", "currency")
             and f["n_distinct"] <= 60 and f["blank_share"] < 0.9]
    if extra:
        A(f"      # context (low-cardinality columns shown to the LLM): TODO pick from {_lst(extra[:8])}")
        A("      # context: []")
        A("      # llm_context: []")
    if "status" in profile:
        st = profile["status"]
        A("    status_map:                   # matched case-insensitively after trim")
        for cls in ("INCLUDE", "CANCELLED", "NOT_APPROVED"):
            A(f"      {cls}: {_lst(st['map'][cls])}")
        if st["unknown"]:
            A(f"      # TODO unrecognised values (they fall to `default`): {_lst(st['unknown'])}")
        A("      default: INCLUDE            # INCLUDE | NOT_APPROVED for unknown values (logged)")
    dup = profile.get("duplicates", {})
    A("    intra_source_dedup: {enabled: false}      # " + (dup.get("hint") or "0 exact invoice/supplier/amount/description/date repeats (spend 0.00). Leave dedup OFF unless the brief says this file was exported twice"))
    A("")
    # ---- fx
    cur = profile.get("currency", {})
    vals = {k: v for k, v in (cur.get("values") or {}).items()}
    others = [c for c in vals if c.upper() != reporting_currency.upper() and c]
    A("fx:")
    A("  files: [" + ", ".join(_q('{input_dir}/' + f) for f in cur.get("fx_files_nearby", [])) + "]   # TODO if a rate table exists")
    A("  plausibility_band: [0.5, 2.0]")
    if others and not cur.get("rate_column") and not cur.get("fx_files_nearby"):
        A("  static_rates: {}              # TODO REQUIRED: units of currency per 1 " + reporting_currency +
          ", e.g. {EUR: 0.92}. Missing -> spend 0 + FX_MISSING")
        for c in others:
            A(f"  #   {c}: TODO   ({vals[c]} rows)")
    else:
        A("  static_rates: {}              # emergency per-currency rates, units per 1 " + reporting_currency)
    A("")
    # ---- exclusion rules
    A("exclusion_rules:                 # ordered; first hit wins. Review candidates from the profile report")
    sug = profile.get("suggested_exclusions") or []
    if sug:
        A("  # SUGGESTED rules (D-43): template-like lines (a repeated leading phrase) in intercompany / tax / payroll / bank /")
        A("  # interest groups; phrases with service words (consult, services, audit...) are never suggested. Row counts and spend")
        A("  # are in the raw file currency. Uncomment what applies (`spendcube profile --accept-suggestions` uncomments all).")
        for x in sug:
            A(f"  {'' if accept_suggestions else '# '}- {{code: NON_PROCUREMENT, field: {x['field']}, regex: {_q(x['regex'])}}}   "
              f"# SUGGESTED {x['category']}: {x['rows']} rows, spend {x['spend']:,.0f}")
    else:
        A("  []")
    A("vendor_propagation: {enabled: true, min_share: 0.9, min_rows: 3, codes: [NON_PROCUREMENT]}")
    A("")
    A("labels: null                     # no labels for a new company")
    A("classification:")
    A("  llm: {enabled: true}")
    A("output: {float_decimals: 2}")
    return "\n".join(L) + "\n"


def main_profile(args) -> int:
    """args: .file, .taxonomy (opt), .draft_config (opt out path), optional .company/.reporting_currency/.fx_dir."""
    p = profile_file(args.file, getattr(args, "taxonomy", None), getattr(args, "fx_dir", None))
    print(format_report(p))
    out = getattr(args, "draft_config", None)
    if out:
        y = draft_config(p, args.file, getattr(args, "taxonomy", None),
                         company=getattr(args, "company", None) or "C",
                         reporting_currency=getattr(args, "reporting_currency", None) or "USD",
                         input_dir=getattr(args, "input_dir", None),
                         accept_suggestions=bool(getattr(args, "accept_suggestions", False)))
        Path(out).parent.mkdir(parents=True, exist_ok=True)
        Path(out).write_text(y, encoding="utf-8")
        print(f"\nDraft config written to {out} (edit the TODOs).")
    return 0
